import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import connectDB from "./src/config/db.js";
import authRoutes from "./src/routes/authRoutes.js";
import shopRoutes from "./src/routes/shopRoutes.js";
import productRoutes from "./src/routes/productRoutes.js";
import listingRoutes from "./src/routes/listingRoutes.js";
import categoryRoutes from "./src/routes/categoryRoutes.js";
import reviewRoutes from "./src/routes/reviewRoutes.js";
import wishlistRoutes from "./src/routes/wishlistRoutes.js";
import adminRoutes from "./src/routes/adminRoutes.js";

dotenv.config();
await connectDB();
const app = express();
app.use(cors({ origin: process.env.CLIENT_URL || "http://localhost:5173" }));
app.use(express.json({ limit: "1mb" }));
app.get("/api/health", (req,res)=>res.json({success:true,message:"SastaKhoj API is running"}));
app.use("/api/auth", authRoutes);
app.use("/api/shops", shopRoutes);
app.use("/api/products", productRoutes);
app.use("/api/listings", listingRoutes);
app.use("/api/categories", categoryRoutes);
app.use("/api/reviews", reviewRoutes);
app.use("/api/wishlist", wishlistRoutes);
app.use("/api/admin", adminRoutes);
app.use((err,req,res,next)=>{ console.error(err); res.status(err.status||500).json({success:false,message:err.message||"Server error"}); });
const PORT=process.env.PORT||5000;
app.listen(PORT,()=>console.log(`SastaKhoj API running on http://localhost:${PORT}`));
